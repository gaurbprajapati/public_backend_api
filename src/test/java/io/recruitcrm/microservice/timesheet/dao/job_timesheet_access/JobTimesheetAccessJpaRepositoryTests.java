	private static final String DUPLICATE_JSON_OBJECT_CONTEXT_CUSTOMIZER_FACTORY = "org.springframework.boot.test.json.DuplicateJsonObjectContextCustomizerFactory";

	@Autowired
	private EntityManager entityManager;

	@Autowired
	private JobTimesheetAccessJpaRepository repository;

	@BeforeEach
	void setUp() {
		this.entityManager
			.createNativeQuery("CREATE TABLE IF NOT EXISTS cst_job_timesheet_access_t ("
					+ "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," + "job_id INTEGER,"
					+ "can_create INTEGER," + "can_edit INTEGER," + "can_delete INTEGER," + "updated_by INTEGER,"
					+ "updated_on INTEGER," + "account_id INTEGER)")
			.executeUpdate();
	}

	private void persistAndFlush(JobTimesheetAccess access) {
		this.entityManager.persist(access);
		this.entityManager.flush();
	}

	private void flushAndClear() {
		this.entityManager.flush();
		this.entityManager.clear();
	}

	@Test
	@DisplayName("findByJobId returns access when job id exists")
	void testFindByJobIdValidJobIdReturnsJobTimesheetAccess() {
		// Given
		JobTimesheetAccess access = JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(1001),
				Integer.valueOf(100));
		this.persistAndFlush(access);

		// When
		Optional<JobTimesheetAccess> result = this.repository.findByJobId(Integer.valueOf(1001));

		// Then
		assertThat(result).isPresent();
		assertThat(result.get().getJobId()).isEqualTo(Integer.valueOf(1001));
		assertThat(result.get().getAccountId()).isEqualTo(Integer.valueOf(100));
		assertThat(result.get().getCanCreate()).isEqualTo(JobTimesheetAccessTestDataFactory.DEFAULT_CAN_CREATE);
	}

	@Test
	@DisplayName("findByJobId returns empty when job id does not exist")
	void testFindByJobIdInvalidJobIdReturnsEmpty() {
		// Given
		Integer nonExistentJobId = Integer.valueOf(9999);

		// When
		Optional<JobTimesheetAccess> result = this.repository.findByJobId(nonExistentJobId);

		// Then
		assertThat(result).isEmpty();
	}

	@Test
	@DisplayName("findByJobId throws when multiple records share the same job id")
	void testFindByJobIdMultipleRecordsThrowsIncorrectResultSize() {
		// Given
		JobTimesheetAccess access1 = JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(2001),
				Integer.valueOf(200));
		this.persistAndFlush(access1);

		JobTimesheetAccess access2 = JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(2001),
				Integer.valueOf(201), JobTimesheetAccessTestDataFactory.CAN_CREATE_DISABLED,
				JobTimesheetAccessTestDataFactory.DEFAULT_CAN_EDIT,
				JobTimesheetAccessTestDataFactory.DEFAULT_CAN_DELETE);
		this.persistAndFlush(access2);

		// When and Then
		assertThatThrownBy(() -> this.repository.findByJobId(Integer.valueOf(2001)))
			.isInstanceOf(org.springframework.dao.IncorrectResultSizeDataAccessException.class);
	}

