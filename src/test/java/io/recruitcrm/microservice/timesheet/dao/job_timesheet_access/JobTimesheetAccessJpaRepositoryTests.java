	@Test
	@DisplayName("findByJobIdsAndAccountId returns all matching rows for account")
	void testFindByJobIdsAndAccountIdReturnsMatchingRows() {
		// Given
		Integer accountId = Integer.valueOf(8100);
		this.persistAndFlush(
				JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(8101), accountId));
		this.persistAndFlush(
				JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(8102), accountId));
		this.persistAndFlush(JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(8103),
				Integer.valueOf(999)));

		// When
		List<JobTimesheetAccess> result = this.repository.findByJobIdsAndAccountId(
				List.of(Integer.valueOf(8101), Integer.valueOf(8102), Integer.valueOf(8103)), accountId);

		// Then
		assertThat(result).hasSize(2);
		assertThat(result).extracting(JobTimesheetAccess::getJobId)
			.containsExactlyInAnyOrder(Integer.valueOf(8101), Integer.valueOf(8102));
	}

