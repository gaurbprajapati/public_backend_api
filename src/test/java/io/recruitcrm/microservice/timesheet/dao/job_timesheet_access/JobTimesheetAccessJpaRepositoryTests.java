	@Test
	@DisplayName("save persists new JobTimesheetAccess")
	void testSaveNewJobTimesheetAccessPersistsSuccessfully() {
		// Given
		JobTimesheetAccess newAccess = JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(8001),
				Integer.valueOf(800));

		// When
		JobTimesheetAccess savedAccess = this.repository.save(newAccess);
		this.flushAndClear();

		// Then
		assertThat(savedAccess.getId()).isNotNull();
		Optional<JobTimesheetAccess> found = this.repository.findByJobIdAndAccountId(Integer.valueOf(8001),
				Integer.valueOf(800));
		assertThat(found).isPresent();
		assertThat(found.get().getJobId()).isEqualTo(Integer.valueOf(8001));
		assertThat(found.get().getAccountId()).isEqualTo(Integer.valueOf(800));
	}

	@Test
	@DisplayName("save updates existing JobTimesheetAccess")
	void testSaveExistingJobTimesheetAccessUpdatesSuccessfully() {
		// Given
		JobTimesheetAccess access = JobTimesheetAccessTestDataFactory.createJobTimesheetAccess(Integer.valueOf(9001),
				Integer.valueOf(900), JobTimesheetAccessTestDataFactory.DEFAULT_CAN_CREATE,
				JobTimesheetAccessTestDataFactory.CAN_CREATE_DISABLED,
				JobTimesheetAccessTestDataFactory.DEFAULT_CAN_DELETE);
		this.persistAndFlush(access);
		Integer accessId = access.getId();

		// When
		access.setCanEdit(JobTimesheetAccessTestDataFactory.DEFAULT_CAN_EDIT);
		access.setCanDelete(Integer.valueOf(1));
		JobTimesheetAccess updatedAccess = this.repository.save(access);
		this.flushAndClear();

		// Then
		assertThat(updatedAccess.getId()).isEqualTo(accessId);
		Optional<JobTimesheetAccess> found = this.repository.findByJobIdAndAccountId(Integer.valueOf(9001),
				Integer.valueOf(900));
		assertThat(found).isPresent();
		assertThat(found.get().getCanEdit()).isEqualTo(JobTimesheetAccessTestDataFactory.DEFAULT_CAN_EDIT);
		assertThat(found.get().getCanDelete()).isEqualTo(Integer.valueOf(1));
	}

