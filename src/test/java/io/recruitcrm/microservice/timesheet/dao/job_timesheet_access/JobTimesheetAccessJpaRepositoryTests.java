	@DisplayName("repository bean is injectable in slice context")
	void testRepositoryBeanIsInjectable() {
		// When
		JobTimesheetAccessJpaRepository resolved = this.repository;

		// Then
		assertThat(resolved).isNotNull().isInstanceOf(JobTimesheetAccessJpaRepository.class);
	}

	static class NoDuplicateJsonWarningBootstrapper extends DefaultTestContextBootstrapper {

		@Override
		protected List<ContextCustomizerFactory> getContextCustomizerFactories() {
			List<ContextCustomizerFactory> factories = new ArrayList<>();
			for (ContextCustomizerFactory factory : super.getContextCustomizerFactories()) {
				if (!JobTimesheetAccessJpaRepositoryTests.DUPLICATE_JSON_OBJECT_CONTEXT_CUSTOMIZER_FACTORY
					.equals(factory.getClass().getName())) {
					factories.add(factory);
				}
			}
			return factories;
		}

	}

	@Configuration
	@EnableTransactionManagement
	@EnableJpaRepositories(basePackageClasses = JobTimesheetAccessJpaRepository.class)
	static class JobTimesheetAccessJpaTestApplication {

		@Bean
		DataSource dataSource() {
			return new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2).build();
		}

		@Bean
		LocalContainerEntityManagerFactoryBean entityManagerFactory(DataSource dataSource) {
			HibernateJpaVendorAdapter vendorAdapter = new HibernateJpaVendorAdapter();
			vendorAdapter.setGenerateDdl(false);
			vendorAdapter.setShowSql(false);

			LocalContainerEntityManagerFactoryBean factoryBean = new LocalContainerEntityManagerFactoryBean();
			factoryBean.setDataSource(dataSource);
			factoryBean.setJpaVendorAdapter(vendorAdapter);
			factoryBean.setPackagesToScan(JobTimesheetAccess.class.getPackageName());
			factoryBean.setJpaPropertyMap(Map.of("hibernate.hbm2ddl.auto", "none"));
			return factoryBean;
		}

		@Bean
		PlatformTransactionManager transactionManager(EntityManagerFactory entityManagerFactory) {
			return new JpaTransactionManager(entityManagerFactory);
		}

	}

